const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('liber', {
  state: cb => ipcRenderer.on('state', (e, s) => cb(s)),
  onBm: cb => ipcRenderer.on('bm', (e, l) => cb(l)),
  onDls: cb => ipcRenderer.on('dls', (e, l) => cb(l)),
  onSettings: cb => ipcRenderer.on('settings', (e, s) => cb(s)),
  onOmni: cb => ipcRenderer.on('focus-omni', cb),
  onFind: cb => ipcRenderer.on('find-omni', cb),
  onFindRes: cb => ipcRenderer.on('findres', (e, r) => cb(r)),
  onHideSug: cb => ipcRenderer.on('hide-sug', cb),
  onOmniPaste: cb => ipcRenderer.on('omni-paste', (e, t) => cb(t)),
  onTabSearch: cb => ipcRenderer.on('tab-search', cb),
  newTab: url => ipcRenderer.invoke('tab:new', url || null),
  newWindow: priv => ipcRenderer.invoke('win:new', !!priv),
  switchTab: id => ipcRenderer.invoke('tab:switch', id),
  closeTab: id => ipcRenderer.invoke('tab:close', id),
  pinTab: (id, on) => ipcRenderer.invoke('tab:pin', id, on),
  grpNew: (name, tabId) => ipcRenderer.invoke('grp:new', name, tabId),
  grpAssign: (tabId, gid) => ipcRenderer.invoke('grp:assign', tabId, gid),
  grpCollapse: (gid, on) => ipcRenderer.invoke('grp:collapse', gid, on),
  grpRename: (gid, name) => ipcRenderer.invoke('grp:rename', gid, name),
  grpColor: gid => ipcRenderer.invoke('grp:color', gid),
  grpDel: gid => ipcRenderer.invoke('grp:del', gid),
  dupTab: id => ipcRenderer.invoke('tab:dup', id),
  closeOthers: id => ipcRenderer.invoke('tab:closeothers', id),
  closeRight: id => ipcRenderer.invoke('tab:closeright', id),
  muteTab: id => ipcRenderer.invoke('tab:mute', id),
  reopen: () => ipcRenderer.invoke('tab:reopen'),
  cycle: d => ipcRenderer.invoke('tab:cycle', d),
  pick: i => ipcRenderer.invoke('tab:pick', i),
  stop: id => ipcRenderer.invoke('tab:stop', id),
  print: id => ipcRenderer.invoke('tab:print', id),
  save: id => ipcRenderer.invoke('tab:save', id),
  source: id => ipcRenderer.invoke('tab:source', id),
  go: (id, input) => ipcRenderer.invoke('tab:nav', { id, input }),
  back: id => ipcRenderer.invoke('tab:back', id),
  reload: id => ipcRenderer.invoke('tab:reload', id),
  page: name => ipcRenderer.invoke('page', name),
  suggest: q => ipcRenderer.invoke('suggest', q),
  zoom: (id, d) => ipcRenderer.invoke('zoom', { id, d }),
  find: (id, q, nx) => ipcRenderer.invoke('find', { id, q, nx }),
  findStop: id => ipcRenderer.invoke('find:stop', id),
  bmToggle: (url, title) => ipcRenderer.invoke('bm:toggle', url, title),
  stSet: patch => ipcRenderer.invoke('st:set', patch),
  siteInfo: () => ipcRenderer.invoke('site:info'),
  siteClearData: () => ipcRenderer.invoke('site:clear-data'),
  srSet: (host, patch) => ipcRenderer.invoke('sr:set', host, patch),
  dataList: () => ipcRenderer.invoke('data:site-list'),
  dataClear: host => ipcRenderer.invoke('data:site-clear', host),
  dataClearAll: () => ipcRenderer.invoke('data:site-clear-all'),
  tabOrder: ids => ipcRenderer.invoke('tab:reorder', ids),
  chrome: on => ipcRenderer.invoke('chrome', on),
  full: () => ipcRenderer.invoke('win:full'),
  reader: () => ipcRenderer.invoke('tab:reader'),
  translate: () => ipcRenderer.invoke('tab:translate'),
  call: m => ipcRenderer.invoke('win:' + m),
})
